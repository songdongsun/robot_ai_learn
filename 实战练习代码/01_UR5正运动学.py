"""对应《05综合实战与仿真》的 UR5 标准 DH 正运动学练习。

长度统一用毫米，计算中的角度用弧度；需要 NumPy。
"""

import numpy as np  # 提供三角函数、数组和矩阵乘法。


# ==================== 模块1：生成一段标准 DH 变换 ====================
def dh_matrix(theta, d, a, alpha):
    """将第 i 个坐标系中的坐标转换到第 i-1 个坐标系。"""
    ct, st = np.cos(theta), np.sin(theta)  # 关节角的余弦、正弦。
    ca, sa = np.cos(alpha), np.sin(alpha)  # 连杆扭角的余弦、正弦。
    # 标准 DH 顺序：绕 Z 转 theta、沿 Z 移 d、沿 X 移 a、绕 X 转 alpha。
    return np.array([
        [ct, -st * ca, st * sa, a * ct],  # 新坐标系各轴及原点在旧 X 方向的分量。
        [st, ct * ca, -ct * sa, a * st],  # 新坐标系各轴及原点在旧 Y 方向的分量。
        [0, sa, ca, d],  # 新坐标系各轴及原点在旧 Z 方向的分量。
        [0, 0, 0, 1],  # 齐次坐标最后一行，使旋转和平移可统一连乘。
    ])


# ==================== 模块2：输入角度，建立六段变换链 ====================
def forward_kinematics(q_deg):
    """输入六个关节角（度），返回第六 DH 坐标系相对于基座的位姿。"""
    q = np.deg2rad(q_deg)  # 将角度转换为三角函数需要的弧度。
    # 每行依次为 theta、d、a、alpha，与函数参数一致，与文档表格列顺序不同。
    # d、a 使用毫米；负 a 是局部轴上的有向距离，并非实体长度为负。
    dh_params = [
        [q[0], 89.16, 0.00, np.pi / 2],  # 第一关节：基座，扭角 +90°。
        [q[1], 0.00, -425.00, 0.0],  # 第二关节：肩部。
        [q[2], 0.00, -392.25, 0.0],  # 第三关节：肘部。
        [q[3], 109.15, 0.00, np.pi / 2],  # 第四关节：腕部，扭角 +90°。
        [q[4], 94.65, 0.00, -np.pi / 2],  # 第五关节：腕部，扭角 -90°。
        [q[5], 82.30, 0.00, 0.0],  # 第六关节：腕部末端。
    ]
    T_total = np.eye(4)  # 从单位矩阵开始，表示尚未经过任何一段变换。
    for i, (theta, d, a, alpha) in enumerate(dh_params, start=1):  # 按顺序读取六行。
        T_step = dh_matrix(theta, d, a, alpha)  # 计算当前相邻坐标系的变换。
        T_total = T_total @ T_step  # 依次得到 T_01、T_02……T_06；顺序不能颠倒。
        # @ 是矩阵乘法；* 是逐元素相乘，不能替代这里的 @。
        print(f"坐标系 {i} 原点在基座中的位置（mm）：{T_total[:3, 3]}")  # 前三行第四列。
    return T_total  # 返回末端位姿，不包含额外夹爪或工具的安装偏移。


# ==================== 模块3：运行零位和基座旋转两组练习 ====================
if __name__ == "__main__":  # 直接运行文件才执行下面代码，导入函数时不执行。
    np.set_printoptions(precision=4, suppress=True)  # 显示四位小数，避免微小数值影响阅读。
    cases = [
        ("练习一：六个关节均为零", [0, 0, 0, 0, 0, 0]),  # 预期 [-817.25, -191.45, -5.49] mm。
        ("练习二：仅第一关节转 90 度", [90, 0, 0, 0, 0, 0]),  # 预期 [191.45, -817.25, -5.49] mm。
    ]
    for title, q_deg in cases:  # 逐一计算两组姿态。
        print(f"\n{title}")  # 标明当前练习。
        print(f"输入关节角（度）：{q_deg}")  # 显示输入，零角度不代表所有杆排成直线。
        T = forward_kinematics(q_deg)  # 六段变换连乘，得到末端相对基座的位姿。
        print("末端齐次变换矩阵：\n", T)  # 输出完整的 4×4 结果。
        print("末端位置 [x, y, z]（mm）：", T[:3, 3])  # 提取末端原点的位置。
        print("末端旋转矩阵：\n", T[:3, :3])  # 三列是末端三个轴在基座中的方向。

# 观察：基座绕 Z 正转 90°，末端位置满足 x'=-y、y'=x、z'=z。
